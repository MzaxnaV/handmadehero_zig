const std = @import("std");
const config = @import("config");

// TIMED_FUNCTION / TIMED_BLOCK
const scoped_gen =
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\{[indent]s}var __t_blk__{[id]d} = {[callee]s}__impl({[id]d}, @src()).Init({[args]s}
    \\{[indent]s}defer __t_blk__{[id]d}.End();
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\
;

// BEGIN_BLOCK / FRAME_MARKER
const src_call_gen =
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\{[indent]s}{[callee]s}__impl({[id]d}, @src(), {[args]s}
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\
;

// END_BLOCK
const call_gen =
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\{[indent]s}{[callee]s}__impl({[id]d}, {[args]s}
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\
;

// No-prefix variants for use inside handmade_debug.zig itself (no Debug. qualifier needed)
const timed_fn_gen_no_prefix =
    \\
    \\{s}// AUTOGENERATED ----------------------------------------------------------
    \\{s}var __t_blk__{} = TIMED_FUNCTION__impl({}, @src()).Init({s}
    \\{s}defer __t_blk__{}.End();
    \\{s}// AUTOGENERATED ----------------------------------------------------------
;

const timed_blk_gen_no_prefix =
    \\
    \\{s}// AUTOGENERATED ----------------------------------------------------------
    \\{s}var __t_blk__{} = TIMED_BLOCK__impl({}, @src()).Init({s}
    \\{s}defer __t_blk__{}.End();
    \\{s}// AUTOGENERATED ----------------------------------------------------------
;

const counter_gen =
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\{[indent]s}{{
    \\{[indent]s}    return {[total]d};
    \\{[indent]s}}}
    \\{[indent]s}// AUTOGENERATED ----------------------------------------------------------
    \\
;

const CallSite = struct {
    pattern: []const u8,
    template: []const u8,
    bumps: bool = true,

    is_counter: bool = false,
};

const call_sites = [_]CallSite{
    .{ .pattern = "Debug.TIMED_FUNCTION(", .template = scoped_gen },
    .{ .pattern = "Debug.TIMED_BLOCK(", .template = scoped_gen },
    .{ .pattern = "Platform.FRAME_MARKER(", .template = src_call_gen },

    .{ .pattern = "Platform.BEGIN_BLOCK(", .template = src_call_gen, .bumps = false },
    .{ .pattern = "Platform.END_BLOCK(", .template = call_gen },
};

const debug_call_sites = [_]CallSite{
    .{ .pattern = "TIMED_FUNCTION(", .template = scoped_gen },
    .{ .pattern = "TIMED_BLOCK(", .template = scoped_gen },
    .{ .pattern = "pub inline fn DEBUG_RECORDS_COUNT() comptime_int", .template = counter_gen, .bumps = false, .is_counter = true },
};

const tag = "AUTOGENERATED";

/// No. of lines the debug imports are required to be within, from the top.
const LINES_SEARCHED_FOR_DEBUG_IMPORT = 2;

const MAX_SOURCE_FILE_BYTES = 1024 * 1024;

pub fn main() !void {
    var gpa: std.heap.DebugAllocator(.{}) = .init;
    defer std.debug.assert(gpa.deinit() == .ok);

    const allocator = gpa.allocator();

    const win32_path = "../win32_handmade.zig";
    const debug_path = "handmade_debug.zig";
    var counter: u32 = 0;

    try rewriteFile(allocator, win32_path, &call_sites, &counter);

    _ = try processDir(allocator, "./", &counter);

    try rewriteFile(allocator, debug_path, &debug_call_sites, &counter);

    std.debug.print("Prepocessing Summary:\n  Generated {d} <...>__impl() calls.\n", .{if (config.PROFILE) counter else 0});
}

fn emitCallSite(w: *std.Io.Writer, comptime sites: []const CallSite, line: []const u8, counter: *u32) !bool {
    inline for (sites) |site| {
        if (std.mem.indexOf(u8, line, site.pattern)) |pos| {
            if (site.is_counter) {
                try w.print(site.template, .{
                    .indent = line[0..pos],
                    .total = if (config.PROFILE) counter.* else 0,
                });
            } else if (config.PROFILE) {
                try w.print(site.template, .{
                    .indent = line[0..pos],
                    .callee = site.pattern[0 .. site.pattern.len - 1],
                    .id = counter.*,
                    .args = line[pos + site.pattern.len ..],
                });
            }
            if (site.bumps) counter.* += 1;

            return true;
        }
    }

    return false;
}

fn rewriteFile(allocator: std.mem.Allocator, path: []const u8, comptime sites: []const CallSite, counter: *u32) !void {
    const buffer = try std.fs.cwd().readFileAlloc(allocator, path, MAX_SOURCE_FILE_BYTES);
    defer allocator.free(buffer);

    // leaves file untouched if it has no call sites
    if (try processFile(allocator, buffer, sites, counter)) |content| {
        defer allocator.free(content);

        // regenerate the AUTOGENERATED blocks in path
        try std.fs.cwd().writeFile(.{ .sub_path = path, .data = content });
    }
}

fn processDir(allocator: std.mem.Allocator, dir_path: []const u8, counter: *u32) !bool {
    var found = false;
    var dir = try std.fs.cwd().openDir(dir_path, .{ .iterate = true });
    defer dir.close();

    var iter = dir.iterate();

    while (try iter.next()) |entry| {
        switch (entry.kind) {
            .file => {
                if (!std.mem.endsWith(u8, entry.name, ".zig")) {
                    continue;
                } else {
                    const buffer = try std.fs.cwd().readFileAlloc(allocator, entry.name, MAX_SOURCE_FILE_BYTES);
                    defer allocator.free(buffer);

                    var reader: std.Io.Reader = .fixed(buffer);

                    for (0..LINES_SEARCHED_FOR_DEBUG_IMPORT) |_| {
                        if (try reader.takeDelimiter('\n')) |line| {
                            if (std.mem.indexOf(u8, line, "const Debug = @import(")) |_| {
                                found = true;

                                if (try processFile(allocator, buffer, &call_sites, counter)) |content| {
                                    defer allocator.free(content);

                                    try std.fs.cwd().writeFile(.{ .sub_path = entry.name, .data = content });
                                }

                                break;
                            }
                        }
                    }
                }
            },
            else => continue,
        }
    }

    return found;
}

fn processFile(allocator: std.mem.Allocator, buffer: []const u8, comptime sites: []const CallSite, counter: *u32) !?[]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    defer aw.deinit();
    const w = &aw.writer;

    var found_call = false;
    var in_generated = false;
    var reader: std.Io.Reader = .fixed(buffer);

    while (try reader.takeDelimiter('\n')) |line| {
        if (std.mem.indexOf(u8, line, tag)) |_| {
            in_generated = !in_generated;
            continue;
        }

        if (in_generated) continue;

        try w.print("{s}\n", .{line});

        if (try emitCallSite(w, sites, line, counter)) found_call = true;
    }

    if (!found_call) return null;

    return try aw.toOwnedSlice();
}
